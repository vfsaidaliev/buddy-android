"""Draws Buddy Full's Vegvisir (an original vector drawing) into Android vector drawables.
Usage: python3 vegvisir.py <res dir>"""
import sys, os

RES = sys.argv[1]

def arm(kind, cx, cy, r0, r1):
    """One stave pointing up from radius r0 to r1 around (cx, cy); kind 0-3 picks its ends."""
    L = r1 - r0
    x = cx
    y0, y1 = cy - r0, cy - r1
    u = L / 22.0  # unit
    p = f"M{x:.2f},{y0:.2f} L{x:.2f},{y1:.2f} "
    if kind == 0:   # trident
        p += (f"M{x-5*u:.2f},{y1+4*u:.2f} L{x+5*u:.2f},{y1+4*u:.2f} "
              f"M{x-5*u:.2f},{y1+4*u:.2f} L{x-5*u:.2f},{y1:.2f} M{x+5*u:.2f},{y1+4*u:.2f} L{x+5*u:.2f},{y1:.2f} ")
    elif kind == 1:  # two bars
        p += (f"M{x-4*u:.2f},{y0-6*u:.2f} L{x+4*u:.2f},{y0-6*u:.2f} "
              f"M{x-4*u:.2f},{y1+3*u:.2f} L{x+4*u:.2f},{y1+3*u:.2f} ")
    elif kind == 2:  # ring at the end
        rr = 2.6 * u
        p = f"M{x:.2f},{y0:.2f} L{x:.2f},{y1+2*rr:.2f} "
        p += (f"M{x-rr:.2f},{y1+rr:.2f} a{rr:.2f},{rr:.2f} 0 1,1 {2*rr:.2f},0 a{rr:.2f},{rr:.2f} 0 1,1 {-2*rr:.2f},0 ")
    else:            # fork with a bar
        p += (f"M{x:.2f},{y1+4*u:.2f} L{x-5*u:.2f},{y1:.2f} M{x:.2f},{y1+4*u:.2f} L{x+5*u:.2f},{y1:.2f} "
              f"M{x-3.5*u:.2f},{y0-7*u:.2f} L{x+3.5*u:.2f},{y0-7*u:.2f} ")
    return p

def symbol(cx, cy, r0, r1, ring):
    arms = ""
    kinds = [0, 1, 2, 3, 0, 3, 2, 1]
    for i, k in enumerate(kinds):
        arms += f'<group android:rotation="{i*45}" android:pivotX="{cx}" android:pivotY="{cy}"><path android:pathData="{arm(k, cx, cy, r0, r1)}" STYLE/></group>\n'
    center = (f'<path android:pathData="M{cx-ring:.2f},{cy:.2f} a{ring:.2f},{ring:.2f} 0 1,1 {2*ring:.2f},0 '
              f'a{ring:.2f},{ring:.2f} 0 1,1 {-2*ring:.2f},0" STYLE/>\n')
    return arms + center

def styled(sym, color, width, alpha_color=None):
    st = f'android:strokeColor="{color}" android:strokeWidth="{width}" android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000"'
    return sym.replace("STYLE", st)

def glowing(sym, glow, core, w):
    """Glow: wide faint strokes under a bright thin one."""
    return (styled(sym, glow % "22", w * 4.2) + styled(sym, glow % "44", w * 2.4) + styled(sym, core, w))

def vector(w, vp, body, aapt=False):
    ns = ' xmlns:aapt="http://schemas.android.com/aapt"' if aapt else ""
    return (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- Vegvisir: Buddy Full\'s own drawing (generated by tools/vegvisir.py) -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"{ns}\n'
            f'    android:width="{w}dp" android:height="{w}dp" android:viewportWidth="{vp}" android:viewportHeight="{vp}">\n{body}</vector>\n')

def obsidian(vp, cx, cy, rad=None):
    """Glossy black obsidian: deep blue-violet sheen and a highlight at the top left."""
    shape = f"M0,0h{vp}v{vp}h-{vp}z" if rad is None else (
        f"M{cx-rad},{cy} a{rad},{rad} 0 1,1 {2*rad},0 a{rad},{rad} 0 1,1 {-2*rad},0")
    return f'''<path android:pathData="{shape}"><aapt:attr name="android:fillColor">
  <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="{vp}" android:endY="{vp}">
    <item android:offset="0" android:color="#FF1A1F33"/><item android:offset="0.45" android:color="#FF0C0E17"/>
    <item android:offset="0.8" android:color="#FF120F22"/><item android:offset="1" android:color="#FF05060A"/>
  </gradient></aapt:attr></path>
<path android:pathData="{shape}"><aapt:attr name="android:fillColor">
  <gradient android:type="radial" android:centerX="{vp*0.72}" android:centerY="{vp*0.78}" android:gradientRadius="{vp*0.55}">
    <item android:offset="0" android:color="#33463A8C"/><item android:offset="1" android:color="#00463A8C"/>
  </gradient></aapt:attr></path>
<path android:pathData="{shape}"><aapt:attr name="android:fillColor">
  <gradient android:type="radial" android:centerX="{vp*0.3}" android:centerY="{vp*0.22}" android:gradientRadius="{vp*0.42}">
    <item android:offset="0" android:color="#40DDE8FF"/><item android:offset="0.5" android:color="#10DDE8FF"/><item android:offset="1" android:color="#00DDE8FF"/>
  </gradient></aapt:attr></path>
'''

def write(name, text):
    with open(os.path.join(RES, "drawable", name + ".xml"), "w") as f:
        f.write(text)

# launcher: 108 viewport, the symbol inside the 66dp safe zone (radius < 33)
write("ic_launcher_background", vector(108, 108, obsidian(108, 54, 54), aapt=True))
sym = symbol(54, 54, 7.5, 30, 4.2)
write("ic_launcher_foreground", vector(108, 108, glowing(sym, "#%s7FB8FF", "#FFE4EEFF", 1.6)))
write("ic_launcher_monochrome", vector(108, 108, styled(sym, "#FFFFFFFF", 2.2)))

# the bubble: a round obsidian stone with the symbol; colours tell its state
bsym = symbol(28, 28, 5, 21, 3)
states = {
    "bubble_face": ("#%s7FB8FF", "#FFE4EEFF"),            # idle: silver-blue
    "bubble_face_thinking": ("#%s5FE3FF", "#FFE8FBFF"),   # working: brighter ice
    "bubble_face_paused": ("#%s8A93A6", "#FF9AA3B5"),     # paused: dull iron
    "bubble_face_brace": ("#%s9FD0FF", "#FFFFFFFF"),      # bracing
    "bubble_face_fired": ("#%sBFE6FF", "#FFFFFFFF"),      # struck
}
for name, (glow, core) in states.items():
    write(name, vector(60, 56, obsidian(56, 28, 28, 26) +
          '<path android:pathData="M2,28 a26,26 0 1,1 52,0 a26,26 0 1,1 -52,0" android:strokeColor="#667FB8FF" android:strokeWidth="0.8" android:fillColor="#00000000"/>\n'
          + glowing(bsym, glow, core, 1.25), aapt=True))
print("ok")
