"""Valkyrie's ornaments, our own drawings: an Urnes-style interlace (two serpents, over and under, beast heads at
the ends) and a Borre-style ring chain, as Android vector drawables. Usage: python3 ornaments.py <res dir> [png dir]"""
import sys, os, math

RES = sys.argv[1]
SILVER, ICE, HALO = "#FFB9C8DE", "#FF8CC8FF", "#FF131623"  # HALO: the card colour, which "cuts" the strand below

def wave(x0, x1, phase, y0=8.0, amp=4.6, period=40.0, step=1.0):
    pts = []
    x = x0
    while x <= x1 + 1e-6:
        pts.append((x, y0 + amp * math.sin(2 * math.pi * x / period + phase)))
        x += step
    return "M" + " L".join(f"{a:.2f},{b:.2f}" for a, b in pts)

def urnes(width=200):
    period = 40.0
    body = []
    st = 'android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000"'
    for ph, col in ((0.0, SILVER), (math.pi, ICE)):
        body.append(f'<path android:pathData="{wave(6, width - 6, ph)}" android:strokeColor="{col}" android:strokeWidth="1.4" {st}/>')
    # crossings every half period: alternately one serpent goes over the other
    k = 1
    x = period / 2
    while x < width - 8:
        ph = 0.0 if k % 2 else math.pi
        col = SILVER if k % 2 else ICE
        seg = wave(x - 5, x + 5, ph, step=0.5)
        body.append(f'<path android:pathData="{seg}" android:strokeColor="{HALO}" android:strokeWidth="4" {st}/>')
        body.append(f'<path android:pathData="{seg}" android:strokeColor="{col}" android:strokeWidth="1.4" {st}/>')
        x += period / 2
        k += 1
    # beast heads: an almond head with an eye, at both ends
    for hx, d in ((6, -1), (width - 6, 1)):
        y = 8.0
        body.append(f'<path android:pathData="M{hx},{y - 2.6} Q{hx + d * 6},{y - 3.2} {hx + d * 7.5},{y} Q{hx + d * 6},{y + 3.2} {hx},{y + 2.6} Z" '
                    f'android:fillColor="{SILVER}"/>')
        body.append(f'<path android:pathData="M{hx + d * 3.6 - 0.8},{y - 0.6} a0.8,0.8 0 1,1 1.6,0 a0.8,0.8 0 1,1 -1.6,0" android:fillColor="{HALO}"/>')
    return width, 16, body

def borre(width=200):
    """A ring chain: overlapping rings, each crossing its neighbour over at the top and under at the bottom."""
    body = []
    st = 'android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000"'
    r, gap, y = 6.0, 9.0, 8.0
    n = int((width - 2 * r - 4) // gap) + 1
    x0 = (width - (n - 1) * gap) / 2

    def arc(cx, a0, a1, steps=14):
        pts = [(cx + r * math.cos(a0 + (a1 - a0) * k / steps), y + r * math.sin(a0 + (a1 - a0) * k / steps)) for k in range(steps + 1)]
        return "M" + " L".join(f"{a:.2f},{b:.2f}" for a, b in pts)

    for i in range(n):
        cx = x0 + i * gap
        col = SILVER if i % 2 == 0 else ICE
        body.append(f'<path android:pathData="{arc(cx, 0, 2 * math.pi, 40)}" android:strokeColor="{col}" android:strokeWidth="1.3" {st}/>')
    # where neighbours cross: the right ring over at the top, the left one over at the bottom
    dy = math.sqrt(r * r - (gap / 2) ** 2)
    for i in range(n - 1):
        a, b = x0 + i * gap, x0 + (i + 1) * gap
        xm = (a + b) / 2
        up_b = math.atan2(-dy, xm - b)
        down_a = math.atan2(dy, xm - a)
        for cx, ang, col in ((b, up_b, SILVER if (i + 1) % 2 == 0 else ICE), (a, down_a, SILVER if i % 2 == 0 else ICE)):
            seg = arc(cx, ang - 0.45, ang + 0.45, 8)
            body.append(f'<path android:pathData="{seg}" android:strokeColor="{HALO}" android:strokeWidth="3.6" {st}/>')
            body.append(f'<path android:pathData="{seg}" android:strokeColor="{col}" android:strokeWidth="1.3" {st}/>')
    return width, 16, body

def write(name, wh):
    w, h, body = wh
    xml = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Valkyrie ornament, our own drawing (generated by tools/ornaments.py) -->\n'
           f'<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="{w}dp" android:height="{h}dp"\n'
           f'    android:viewportWidth="{w}" android:viewportHeight="{h}">\n' + "\n".join(body) + "\n</vector>\n")
    with open(os.path.join(RES, "drawable", name + ".xml"), "w") as f:
        f.write(xml)

write("orn_urnes", urnes())
write("orn_borre", borre())
print("ok")
